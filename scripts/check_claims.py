"""Claims lint. Exit code 0 only when every rule passes.

Rules
  1  No em dash or en dash anywhere in text files.
  2  No spaced hyphen used as a dash in prose.
  3  The words Claude and Anthropic appear nowhere, including commit messages.
  4  Apart from the technical term finite population correction, the words population, abundance and absent or absence appear in published text only in a
     negated sentence (a sentence that also holds no, not, never, neither, nor, without, cannot,
     or does not).
  5  Every section of a published results document that holds a percent figure also names its
     data label (SYNTHETIC, BORROWED or PUBLISHED).
  6  Published documents with numbers (README.md, results/RESULTS.md, docs/STATUS.md, docs/PITCH.md) carry the
     generated marker, so no number is typed by hand. Other documents hold no digit followed by a
     percent sign.
  7  Only the emojis allowed by the style rule appear in published text.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEXT_SUFFIXES = {".md", ".py", ".txt", ".toml", ".json", ".csv", ".cfg", ".yml", ".yaml"}
SKIP_DIRS = {".git", "__pycache__", ".pytest_cache", "data", "figures", ".venv"}
ALLOWED_EMOJI = set("🌷🌸🍋🌿")
MARKER = "generated by scripts/make_docs.py"
GENERATED = ["README.md", "results/RESULTS.md", "docs/STATUS.md", "docs/PITCH.md"]
LABELS = ("SYNTHETIC", "BORROWED", "PUBLISHED")
NEGATION = re.compile(r"\b(no|not|never|neither|nor|without|cannot|does not|do not|is not|are not|nothing)\b", re.I)
CLAIM_WORDS = re.compile(r"\b(population|abundance|absent|absence)\b", re.I)
EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿]")
SELF = Path(__file__).resolve()


def files():
    for p in ROOT.rglob("*"):
        if p.is_file() and p.suffix in TEXT_SUFFIXES and not (set(p.relative_to(ROOT).parts) & SKIP_DIRS) and p.resolve() not in (SELF, ROOT / "tests" / "test_claims.py"):
            yield p


def published():
    for p in ROOT.glob("*.md"):
        yield p
    for sub in ("docs", "results"):
        yield from (ROOT / sub).glob("*.md")


def run() -> list[str]:
    errors: list[str] = []
    for p in files():
        rel = p.relative_to(ROOT)
        try:
            txt = p.read_text(encoding="utf8")
        except UnicodeDecodeError:
            continue
        if p.suffix == ".json" and rel.parts[0] != "results":
            pass
        for n, line in enumerate(txt.splitlines(), 1):
            if "—" in line or "–" in line:
                errors.append(f"{rel}:{n} dash character")
            if p.suffix == ".md" and re.search(r"\S - \S", line) and not line.lstrip().startswith(("|", "- ", "* ")):
                errors.append(f"{rel}:{n} spaced hyphen used as a dash")
            if re.search(r"claude|anthropic", line, re.I):
                errors.append(f"{rel}:{n} banned name")
    log = subprocess.run(["git", "log", "--format=%an %ae %s %b"], cwd=ROOT, capture_output=True, text=True).stdout
    if re.search(r"claude|anthropic", log, re.I):
        errors.append("git history: banned name in a commit")
    for p in published():
        rel = str(p.relative_to(ROOT)).replace("\\", "/")
        txt = p.read_text(encoding="utf8")
        for sent in re.split(r"(?<=[.!?])\s+|\n", txt):
            probe = re.sub(r"finite population( correction)?", "", sent, flags=re.I)
            if CLAIM_WORDS.search(probe) and not NEGATION.search(sent):
                errors.append(f"{rel}: claim word outside a negated sentence: {sent.strip()[:80]}")
        for ch in EMOJI.findall(txt):
            if ch not in ALLOWED_EMOJI:
                errors.append(f"{rel}: emoji {ch} not allowed")
        if rel in GENERATED:
            if MARKER not in txt:
                errors.append(f"{rel}: missing generated marker")
            sections = re.split(r"(?m)^#{1,6} ", txt)
            for sec in sections[1:] if len(sections) > 1 else sections:
                if re.search(r"\d(\.\d+)?\s*%", sec) and not any(l in sec for l in LABELS):
                    errors.append(f"{rel}: section with a percent figure lacks a data label: {sec.splitlines()[0][:60]}")
        elif re.search(r"\d\s*%", txt):
            errors.append(f"{rel}: percent figure typed by hand")
    return errors


if __name__ == "__main__":
    errs = run()
    for e in errs:
        print(e)
    print(f"{len(errs)} issue(s)")
    sys.exit(1 if errs else 0)
