def load(name):
    return json.load(open(ROOT / "results" / name, encoding="utf8"))


def pct(x, d=2):
    return f"{100 * x:.{d}f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def style():
    plt.rcParams.update({"figure.facecolor": PEARL, "axes.facecolor": PEARL, "savefig.facecolor": PEARL,
                         "axes.edgecolor": DEEP, "axes.labelcolor": DEEP, "text.color": DEEP, "xtick.color": DEEP,
                         "ytick.color": DEEP, "font.family": "serif", "axes.grid": True, "grid.color": SAKURA,
                         "axes.prop_cycle": plt.cycler(color=PALE)})


def finish(fig, ax, name, label, title, ylabel, xlabel="Review budget (events)"):
    ax.set_title(title, color=ROSE)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.legend(frameon=False, fontsize=8)
    fig.text(0.01, 0.01, f"Data label: {label}", fontsize=8, color=DEEP)
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    fig.savefig(ROOT / "figures" / name, dpi=150)
    plt.close(fig)


